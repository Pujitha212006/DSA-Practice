#include <iostream>
using namespace std;

int main() {
   
    int a = 10;
    int b = 10;

    int x = 10;
    int y = 10;

    cout<< ++a << endl;// pre increment
    cout<< b++ << endl;// post increment
    
    cout<< x-- << endl;// post decrement
    cout<< --y << endl;// pre decrement
    return 0;

}
